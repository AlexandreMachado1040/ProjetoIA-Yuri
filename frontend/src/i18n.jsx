// ── Contexto ────────────────────────────────────────────────────────────────
const I18nContext = createContext(null)

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => {
    const salvo = typeof localStorage !== 'undefined' && localStorage.getItem('aurova_lang')
    return DICT[salvo] ? salvo : 'pt'
  })
  const setLang = useCallback((l) => {
    if (!DICT[l]) return
    try { localStorage.setItem('aurova_lang', l) } catch { /* storage indisponível */ }
    setLangState(l)
  }, [])

  const t = useCallback((chave, vars) => {
    let s = DICT[lang][chave] ?? DICT.pt[chave] ?? chave
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v)
    return s
  }, [lang])

  const locale = LOCALES[lang]
  const fmt = useCallback((v, dec = 1) =>
    (v === null || v === undefined || Number.isNaN(+v))
      ? '—'
      : (+v).toLocaleString(locale, { minimumFractionDigits: dec, maximumFractionDigits: dec }),
  [locale])

  const valor = useMemo(() => ({
    lang, setLang, t, locale, fmt,
    meses: MESES_ABREV[lang], mesesNome: MESES_NOME[lang],
  }), [lang, setLang, t, locale, fmt])

  return <I18nContext.Provider value={valor}>{children}</I18nContext.Provider>
}

export function useI18n() {
  return useContext(I18nContext)
}

// ── Tradução de rótulos gerados pelo motor (backend em PT-BR) ───────────────
const RE_SUJIDADE = /^Perdas sujidade \((.+)\)$/
const RE_CABO     = /^Perdas cabo CC \(ôhmica, (.+) STC\)$/
const RE_DEG      = /^Perdas degradação \(ano (\d+), (.+)\/ano\)$/
const RE_INDISP   = /^Perdas indisponibilidade \((.+)\)$/
const RE_SONDA    = /^SONDA\/INPE TGY (\S*) \(medido\)$/

export function traduzirRotuloMotor(label, t) {
  if (!label) return label
  let m
  if ((m = RE_SUJIDADE.exec(label))) return t('motor.sujidade_p', { v: m[1] })
  if ((m = RE_CABO.exec(label)))     return t('motor.cabo_p',     { v: m[1] })
  if ((m = RE_DEG.exec(label)))      return t('motor.deg_p',      { n: m[1], v: m[2] })
  if ((m = RE_INDISP.exec(label)))   return t('motor.indisp_p',   { v: m[1] })
  const direto = t(`motor.${label}`)
  return direto === `motor.${label}` ? label : direto
}

export function traduzirFonte(fonte, t) {
  if (!fonte) return fonte
  let m
  if ((m = RE_SONDA.exec(fonte))) return t('fonte.sonda', { est: m[1] })
  if (fonte === 'NASA POWER (ao vivo)')     return t('fonte.nasa_vivo')
  if (fonte === 'NASA POWER')               return t('fonte.nasa')
  if (fonte === 'Fallback climatológico')   return t('fonte.fallback')
  return fonte
}

// Nomes agregados do modo planta gerados pelo motor em PT
// (ex.: "3 sub-arranjos", "3 inversores (CSI-250K ×2, Huawei ×1)").
const RE_SUBS = /^(\d+) sub-arranjos$/
const RE_INVS = /^(\d+) inversores \((.+)\)$/

export function traduzirNomePlanta(nome, t) {
  if (!nome) return nome
  let m
  if ((m = RE_SUBS.exec(nome))) return t('fonte.subs', { n: m[1] })
  if ((m = RE_INVS.exec(nome))) return t('fonte.invs', { n: m[1], lista: m[2] })
  return nome
}
